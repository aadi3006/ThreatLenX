// ─── Alert Model & Lifecycle ────────────────────────────────────────────────

export type AlertStatus = 'NEW' | 'ACKNOWLEDGED' | 'RESOLVED' | 'SUPPRESSED';

export interface Alert {
  /** Canonical unique identifier (e.g. 'alt-sec-1710000000000-abcd1234') */
  id: string;

  /** ID of the detection rule that generated this alert */
  ruleId: string;

  /** Version number of the detection rule that generated this alert */
  ruleVersion?: number;

  /** Name of the detection rule */
  ruleName: string;

  /** Alert title */
  title: string;

  /** Detailed explanation of what was detected */
  description: string;

  /** Alert severity */
  severity: Severity;

  /** Current lifecycle status */
  status: AlertStatus;

  /** Security category */
  category: EventCategory;

  /** ISO 8601 UTC timestamp when alert was generated */
  createdAt: string;

  /** Timestamp of the earliest contributing SecurityEvent */
  firstSeenAt: string;

  /** Timestamp of the most recent contributing SecurityEvent */
  lastSeenAt: string;

  /** Number of occurrences / events deduplicated into this alert */
  occurrenceCount: number;

  /** Array of contributing SecurityEvent IDs for complete provenance */
  sourceEventIds: string[];

  /** Initial triggering event ID */
  primaryEventId: string;

  /** Referenced asset ID */
  assetId?: string;

  /** Referenced user ID */
  userId?: string;

  /** Matched IOC IDs */
  iocIds?: string[];

  /** Associated MITRE technique ID */
  mitreTechniqueId?: string;

  /** Associated MITRE tactic */
  mitreTactic?: string;

  /** Optional correlated incident association */
  incidentId?: string;

  /** Deterministic fingerprint for deduplication & throttling */
  fingerprint: string;

  /** Analyst triage notes */
  analystNotes?: string;

  /** Actor who acknowledged the alert */
  acknowledgedBy?: string;

  /** ISO 8601 UTC timestamp of acknowledgement */
  acknowledgedAt?: string;

  /** Actor who acknowledged or resolved the alert */
  resolvedBy?: string;

  /** ISO 8601 UTC timestamp of resolution */
  resolvedAt?: string;

  /** Extensible domain metadata */
  metadata?: Record<string, unknown>;

  // Backward-compatibility aliases
  timestamp?: string;
  source?: string;
  sourceIp?: string;
  destIp?: string;
  rawPayload?: Record<string, unknown>;
}

