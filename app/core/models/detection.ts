import type { Severity } from './incident';
import type { EventCategory, EventSeverity, EventSourceType } from './event';

// ─── Rule Conditions & Logical Grouping ────────────────────────────────────────

export type RuleConditionOperator =
  | 'EQUALS'
  | 'NOT_EQUALS'
  | 'CONTAINS'
  | 'NOT_CONTAINS'
  | 'STARTS_WITH'
  | 'ENDS_WITH'
  | 'GREATER_THAN'
  | 'LESS_THAN'
  | 'GREATER_THAN_OR_EQUAL'
  | 'LESS_THAN_OR_EQUAL'
  | 'IN_LIST'
  | 'NOT_IN_LIST'
  | 'EXISTS';

export interface RuleCondition {
  /** Target field in the SecurityEvent (e.g. 'eventType', 'category', 'severity', 'commandLine', 'domain') */
  field: string;
  /** Comparison operator */
  operator: RuleConditionOperator;
  /** Target value to evaluate against */
  value?: string | number | boolean | string[] | number[];
}

export type LogicalOperator = 'AND' | 'OR';

export interface RuleConditionGroup {
  /** Logical junction operator across child conditions or groups */
  operator: LogicalOperator;
  /** Optional negation of the entire group */
  negate?: boolean;
  /** Child conditions or nested condition groups */
  conditions: (RuleCondition | RuleConditionGroup)[];
}

// ─── Rule Lifecycle & Versioning ────────────────────────────────────────────

export type RuleLifecycleStatus =
  | 'DRAFT'
  | 'VALIDATING'
  | 'TESTING'
  | 'PUBLISHED'
  | 'ENABLED'
  | 'DISABLED'
  | 'DEPRECATED';

export type RuleVersionStatus = 'ACTIVE' | 'ARCHIVED' | 'SUPERSEDED';

// ─── Canonical Detection Rule Model ─────────────────────────────────────────

export interface DetectionRule {
  /** Unique entity ID (e.g. 'DET-AUTH-001' or 'rule-1710000000-abcd') */
  id: string;

  /** Stable rule lineage identifier (e.g. 'DET-AUTH-001') */
  ruleId?: string;

  /** Monotonic rule version integer (e.g. 1, 2, 3) */
  version?: number;

  /** Human-readable rule title */
  name: string;

  /** Technical description and analyst guidance */
  description: string;

  /** Lifecycle status of the rule */
  status?: RuleLifecycleStatus;

  /** Whether the rule is actively evaluated on incoming telemetry (synchronized with status === 'ENABLED') */
  enabled: boolean;

  /** Severity assigned to alerts generated by this rule */
  severity: Severity;

  /** Primary event category targeted by this rule */
  category: EventCategory;

  /** Optional event type filter for fast pre-filtering (e.g. ['PROCESS_CREATE']) */
  eventTypes?: string[];

  /** Declarative conditions that must evaluate to TRUE */
  conditions: (RuleCondition | RuleConditionGroup)[];

  /** Throttling / deduplication window in milliseconds (default 900,000ms = 15 min) */
  timeWindowMs?: number;

  /** Threshold count of matching events before alerting (default 1) */
  threshold?: number;

  /** Associated primary MITRE ATT&CK technique identifier (e.g. 'T1059.001') */
  mitreTechniqueId?: string;

  /** Associated secondary or multiple MITRE ATT&CK technique identifiers */
  mitreTechniqueIds?: string[];

  /** Associated MITRE ATT&CK tactic */
  mitreTactic?: string;

  /** Search tags (e.g. ['credential_access', 'sysmon', 'blacktide']) */
  tags?: string[];

  /** Author or source of the rule */
  author?: string;

  /** Author user ID or analyst username */
  authorId?: string;

  /** Version status */
  versionStatus?: RuleVersionStatus;

  /** Description of changes introduced in this version */
  changeDescription?: string;

  /** ISO 8601 UTC timestamp of creation */
  createdAt: string;

  /** ISO 8601 UTC timestamp of last modification */
  updatedAt: string;

  /** ISO 8601 UTC timestamp of publication */
  publishedAt?: string;

  /** ISO 8601 UTC timestamp when disabled */
  disabledAt?: string;

  /** ISO 8601 UTC timestamp when deprecated */
  deprecatedAt?: string;
}

/** Historical immutable snapshot of a specific rule version */
export interface DetectionRuleVersion {
  id: string; // e.g. `${ruleId}-v${version}`
  ruleId: string;
  version: number;
  rule: DetectionRule;
  authorId?: string;
  author?: string;
  changeDescription: string;
  publishedAt: string;
  createdAt: string;
}

